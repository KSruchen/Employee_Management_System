--------------------------------------------------------------------------------
-- STEP 1: CREATE DIRECTORATE TABLE
--------------------------------------------------------------------------------
CREATE TABLE DIRECTORATE (
  DIRECTORATE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(50) NOT NULL
);

--------------------------------------------------------------------------------
-- STEP 2: CREATE DIVISION TABLE
--------------------------------------------------------------------------------
CREATE TABLE DIVISION (
  DIVISION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(50) NOT NULL,
  DIRECTORATE_ID NUMBER REFERENCES DIRECTORATE(DIRECTORATE_ID)
);

--------------------------------------------------------------------------------
-- STEP 3: CREATE EMPLOYEE TABLE (PERSONAL DETAILS ONLY)
--------------------------------------------------------------------------------
CREATE TABLE EMPLOYEE (
    EMP_ID VARCHAR2(10) PRIMARY KEY,
    EMP_NAME VARCHAR2(50),
    ADDRESS VARCHAR2(100),
    PHONE VARCHAR2(20),
    AGE NUMBER,
    GENDER VARCHAR2(10),
    EMAIL VARCHAR2(100),

    -- Directorate and Division for employee's primary/current assignment
    DIRECTORATE VARCHAR2(50),
    DIVISION VARCHAR2(50),
    DIRECTORATE_ID NUMBER,
    DIVISION_ID NUMBER,

    CONSTRAINT FK_EMP_DIR FOREIGN KEY (DIRECTORATE_ID)
        REFERENCES DIRECTORATE(DIRECTORATE_ID),

    CONSTRAINT FK_EMP_DIV FOREIGN KEY (DIVISION_ID)
        REFERENCES DIVISION(DIVISION_ID)
);

--------------------------------------------------------------------------------
-- STEP 4: CREATE EMPLOYEE_ROLE TABLE (WITH DIRECTORATE & DIVISION)
--------------------------------------------------------------------------------
CREATE TABLE EMPLOYEE_ROLE (
    ROLE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMP_ID VARCHAR2(10) NOT NULL,
    ROLE_NAME VARCHAR2(50),
    ROLE_NUMBER VARCHAR2(20),
    FROM_DATE DATE,
    TO_DATE DATE,
    
    -- Each role can have its own directorate and division
    DIRECTORATE_ID NUMBER,
    DIVISION_ID NUMBER,

    CONSTRAINT FK_ROLE_EMP
        FOREIGN KEY (EMP_ID)
        REFERENCES EMPLOYEE(EMP_ID)
        ON DELETE CASCADE,
        
    CONSTRAINT FK_ROLE_DIR
        FOREIGN KEY (DIRECTORATE_ID)
        REFERENCES DIRECTORATE(DIRECTORATE_ID),
        
    CONSTRAINT FK_ROLE_DIV
        FOREIGN KEY (DIVISION_ID)
        REFERENCES DIVISION(DIVISION_ID)
);

