FROM EMPLOYEE E
ORDER BY E.EMP_ID;

SELECT ER.ROLE_ID, ER.EMP_ID, ER.ROLE_NAME, D.NAME AS DIRECTORATE, DIV.NAME AS DIVISION
FROM EMPLOYEE_ROLE ER
LEFT JOIN DIRECTORATE D ON ER.DIRECTORATE_ID = D.DIRECTORATE_ID
LEFT JOIN DIVISION DIV ON ER.DIVISION_ID = DIV.DIVISION_ID
ORDER BY ER.EMP_ID, ER.FROM_DATE DESC;
